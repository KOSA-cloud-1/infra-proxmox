#!/bin/bash

# =========================================================
# Terraform Init
# =========================================================
echo "=================================================="
echo "[1/3] terraform init 시작"
echo "=================================================="

terraform init

if [ $? -ne 0 ]; then
    echo "❌ terraform init 실패"
    exit 1
fi

echo "✅ terraform init 완료"
sleep 5

# =========================================================
# Terraform Plan
# =========================================================
echo "=================================================="
echo "[2/3] terraform plan 시작"
echo "=================================================="

terraform plan

if [ $? -ne 0 ]; then
    echo "❌ terraform plan 실패"
    exit 1
fi

echo "✅ terraform plan 완료"
sleep 5

# =========================================================
# Deploy Script 실행
# =========================================================
echo "=================================================="
echo "[3/3] deploy.sh 실행"
echo "=================================================="

chmod +x deploy.sh
./deploy.sh

if [ $? -ne 0 ]; then
    echo "❌ deploy.sh 실행 실패"
    exit 1
fi

echo "✅ deploy.sh 실행 완료"

# =========================================================
# 전체 완료
# =========================================================
echo "=================================================="
echo "🎉 전체 작업 완료"
echo "=================================================="
